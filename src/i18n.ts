const dicts = { en, ar };

export type Params = Record<string, string | number>;

export function translate(lang: Lang, key: Key, params?: Params) {
  let s: string = dicts[lang][key] ?? en[key];
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

const locale = (lang: Lang) => (lang === "ar" ? "ar-BH-u-nu-latn" : "en-BH");

export function money(lang: Lang, n: number) {
  const whole = Math.abs(n - Math.round(n)) < 0.0005;
  const num = new Intl.NumberFormat(locale(lang), {
    minimumFractionDigits: whole ? 0 : 3,
    maximumFractionDigits: whole ? 0 : 3,
  }).format(n);
  return lang === "ar" ? `${num} د.ب` : `BD ${num}`;
}

/** Month 0 is November 2026. */
export function monthLabel(lang: Lang, idx: number) {
  const d = new Date(2026, 10 + idx, 1);
  return new Intl.DateTimeFormat(locale(lang), { month: "long", year: "numeric" }).format(d);
}

export function useT() {
  const lang = useDemo((s) => s.lang);
  return {
    lang,
    t: (key: Key, params?: Params) => translate(lang, key, params),
    m: (n: number) => money(lang, n),
    mon: (i: number) => monthLabel(lang, i),
  };
}
